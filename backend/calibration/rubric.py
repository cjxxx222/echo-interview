"""校准实验评分量表（rubric）—— 4 维度 × 5 档，每档配行为锚定描述。

双重用途：
1. 真人面试官的培训材料（实验前对齐口径，避免「5 个人 5 套标准」）
2. 盲评 Web 表单的选项内容

设计要点：锚定描述写「可观察的行为」，不写形容词。
「5 分」不是「很好」，而是「被追问 2 层仍有量化数据和取舍」这种可判定的行为。
"""

# 每档 1-5 分；结构与岗位匹配维度按回答内容判定，深度按被追问后的表现判定
RUBRIC: dict[str, dict[int, str]] = {
    "structure": {
        1: "没有结构：语气词开头、内容碎片化、明显跑题或未回应问题",
        2: "有开头无收束：说了些相关内容但主线和问题对不上，听者抓不到要点",
        3: "基本对题：覆盖了主要内容，但平铺直叙、没有分层，需要听者自己整理",
        4: "有结构：结论先行或有清晰分层（如背景-动作-结果），偶有冗余",
        5: "结构完整：结论先行、分层展开、结尾收束；信息密度高且不跑题",
    },
    "depth": {
        1: "被追问后仍给不出任何细节、数据或具体场景",
        2: "能补充一些细节，但停留在流程描述，无数据、无取舍",
        3: "有关键细节和数据，但被追问一层后开始含糊或重复原话",
        4: "被追问 1-2 层仍有细节支撑，能讲清部分取舍理由",
        5: "被追问 2 层以上仍有量化数据和具体场景，讲得清「为什么这么做、放弃了什么、复盘了什么」",
    },
    "job_match": {
        1: "回答与岗位要求基本无关，或术语使用错误",
        2: "有关联但牵强：话题绕不开自身经历，接不上 JD 关心的能力",
        3: "覆盖了岗位关心的部分要点，术语基本准确，关联需要听者自己建立",
        4: "主动把话题拉回岗位能力项，术语准确，能举出与 JD 相关的证据",
        5: "每段回答都能落到 JD 要求的具体能力上，术语精准且有岗位视角的取舍判断",
    },
    "written_expression": {
        1: "大段口语、语气词和重复句占篇幅，难以读出有效信息",
        2: "有明显口语废词和冗余段落，但意思能懂",
        3: "通顺但有冗余：同样的信息说了两遍，或一句话能说清的事绕了三句",
        4: "简洁清晰，偶有重复，段落边界清楚",
        5: "高度简洁、无废词、分段清晰，信息密度接近书面表达",
    },
}

SCALE_LABEL = "1-5 分（行为锚定，见各档描述）"


def rubric_for_prompt() -> str:
    lines = []
    for dim, levels in RUBRIC.items():
        lines.append(f"### {dim}")
        for score in sorted(levels):
            lines.append(f"- {score} 分：{levels[score]}")
    return "\n".join(lines)
